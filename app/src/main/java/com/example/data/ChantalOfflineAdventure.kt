package com.example.data

import com.example.domain.*

/** Small authored fallback pool. These are local stories, never presented as model output. */
object ChantalOfflineAdventure {
    fun decorate(base: ChantalStoryEpisode): ChantalStoryEpisode {
        if (base.isFiller) return base
        val scene = (base.journeyNumber - 1).mod(3)
        val opening = "Утром Шанталь дошла до указателя «${base.regionTitleRu}» и свернула на боковую тропу."
        val lines = when (scene) {
            0 -> listOf(opening,
                "У ручья сидел мышонок-пекарь, а его тележка с хлебом застряла между двумя камнями.",
                "К вечеру хлеб ждали рабочие, чинившие лесной мост, и пекарь боялся подвести всю артель.",
                "Шанталь предложила сперва съесть груз, чтобы тележка стала легче, но мышонок не оценил хозяйственную смекалку.",
                "Тогда она обошла камни и заметила, что колесо держит не валун, а мокрый корень под ним.",
                "Перегрызать корень живого дерева она не стала и подложила под ось плоскую дощечку.",
                "Мышонок потянул за ручки, лисёнок упёрлась плечом, и тележка выбралась на берег.",
                "Один каравай всё-таки скатился в воду, зато его сразу занял важный селезень.",
                "Шанталь проводила пекаря до моста и увидела, как рабочие разделили ещё тёплый хлеб.",
                "За помощь мышонок угостил её корочкой с тмином и попросил передать дома простое спасибо.",
                "У камина она призналась, что спасать чужой ужин оказалось приятнее, чем придумывать способ его украсть.")
            1 -> listOf(opening,
                "На ветке висел синий фонарь, который светил только с закрытой дверцей.",
                "Под ним ёжик чинил сапог и каждый раз вздрагивал, когда кто-нибудь пытался заглянуть внутрь.",
                "Он объяснил, что светлячки согласились помогать до рассвета, если их не будут беспокоить.",
                "Шанталь уже подняла лапу к защёлке, но остановилась и спросила, чем можно помочь без света в глаза.",
                "Ёжик потерял толстую иглу в траве, а без неё не мог закончить сапог для завтрашней дороги.",
                "Лисёнок легла на живот и заметила металлический блеск у самого корня.",
                "Она достала иглу сухой веточкой и гордо объявила себя самой низкорослой искательницей сокровищ.",
                "Когда работа была закончена, светлячки сами приоткрыли дверцу и выстроились в светящуюся стрелку до тропы.",
                "Ёжик ушёл в починенных сапогах, а Шанталь проводила его до поворота, не пытаясь никого посадить в банку.",
                "Дома она сказала, что иногда волшебство остаётся рядом именно потому, что его не стараются присвоить.")
            else -> listOf(opening,
                "В пустой сторожке она нашла медный чайник, который сердито свистел над холодной печью.",
                "Внутри застрял крошечный дух пара и требовал немедленно вызвать главного по кипятку.",
                "Шанталь назвалась временной заместительницей по тёплым лужам и предложила сначала объяснить беду.",
                "Дух забрался в чайник погреться, а крышка захлопнулась от ветра.",
                "Лисёнок попробовала потянуть за ручку крышки, но только ударилась носом и рассердилась.",
                "Потом она заметила, что носик забит сухим липовым листом.",
                "Стоило вынуть лист, как дух вылетел тонкой струйкой и превратился в прозрачного воробья.",
                "Он хотел подарить спасительнице вечную бурю в стакане, но Шанталь вежливо попросила обыкновенный тёплый чай.",
                "Они выпили по чашке, после чего дух вернулся к реке, а лисёнок закрыла окно сторожки от сквозняка.",
                "У себя дома она проверила чайник и предупредила его, что должность главного по кипятку уже занята.")
        }
        val labels = when (scene) {
            0 -> listOf("Похвалить, что помогла пекарю", "Обсудить, как вытолкнуть тележку безопаснее", "Спросить, взял ли селезень хлеб в долг")
            1 -> listOf("Поддержать её уважение к светлячкам", "Расспросить, как она заметила иглу", "Поддразнить титул искательницы сокровищ")
            else -> listOf("Порадоваться спасению духа", "Разобраться, почему крышку заклинило", "Назначить Шанталь хранительницей чайника")
        }
        val reactions = when (scene) {
            0 -> listOf("Шанталь улыбается и откладывает для мышонка яблоко на следующую встречу.", "В следующий раз возьму верёвку, — решает Шанталь, потирая плечо.", "Он обещал расплатиться кряканьем, — фыркает она и изображает важную утку.")
            1 -> listOf("Пусть светят, как им удобно, — кивает Шанталь и прикрывает штору.", "Она показывает, как надо смотреть вдоль травы, чтобы заметить блеск.", "Титул длиннее меня самой, — смеётся лисёнок и вытягивает хвост.")
            else -> listOf("Теперь он снова у реки, — говорит Шанталь и греет лапы о чашку.", "Дело было в листе и сквозняке, — объясняет она и проверяет защёлку окна.", "Тогда чайник будет моим первым подчинённым, — торжественно объявляет Шанталь.")
        }
        val deltas = listOf(ChantalTraits(0, 2, 0, 1, 0, 0), ChantalTraits(2, 0, 0, 0, 1, 0), ChantalTraits(0, 0, 2, 0, 0, 1))
        return base.copy(titleRu = listOf("Хлеб для мостовой артели", "Свет, который нельзя забрать", "Главная по кипятку")[scene],
            storyTextRu = lines.joinToString(" "), mapNoteRu = "Место встречи: ${base.regionTitleRu}",
            choices = (0..2).map { ChantalChoiceOption(labels[it], reactions[it], deltas[it]) })
    }

    fun previewBase() = ChantalStoryEpisode(
        id = "preview_only", journeyNumber = 1, titleRu = "Пробное приключение", storyTextRu = "", mapNoteRu = "",
        regionTitleRu = "Янтарная дубрава", npcNameRu = "Корвус", stayedInSameRegion = false, isFiller = false,
        lootItem = ChantalInventoryLootItem(id = "preview_only_loot", titleRu = "Без награды", category = ChantalLootCategory.TRINKET,
            descriptionRu = "Пробный рассказ", sellPriceCoins = 0, foundAtRegionRu = "Янтарная дубрава", foundDateIso = ""),
        coinsEarned = 0, causesExhaustion45 = false, debtAmountCoins = 0, badNewsRu = "", choices = emptyList())
}
