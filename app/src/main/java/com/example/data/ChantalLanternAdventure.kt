    /** Replaying reconciliation never grants currency; facts have stable IDs and journal sources. */
    fun consequences(initial: JSONObject, journal: List<ChantalStoryEpisode>): JSONObject {
        var memory = initial
        fun fact(stage: Int, id: String, text: String) = JSONObject().put("id", id)
            .put("sourceEpisodeId", "$PREFIX$stage").put("descriptionRu", text)
        val first = accepted(journal, 0)
        if (first != null) {
            val promised = choice(first, 0) == 0
            val done = accepted(journal, 3) != null
            if (promised) memory = ChantalWorldMemory.withFact(memory, "promises",
                fact(0, "lantern_song", "Помочь Брамблу вернуть песню переправы").put("status", if (done) "resolved" else "open"))
            memory = ChantalWorldMemory.withFact(memory, "relationships", fact(0, "bramble", if (done) "Вместе вернули письмо и зажгли фонарь" else "Выслушала историю о сестре Брамбла"))
        }
        if (accepted(journal, 1) != null) {
            memory = ChantalWorldMemory.withFact(memory, "relationships", fact(1, "corvus", "Корвус поделился мелодией старой переправы"))
            if (choice(accepted(journal, 1), 1) == 0) memory = ChantalWorldMemory.withFact(memory, "magicItems",
                fact(1, "silver_thread", "Серебряная нитка колокольчика").put("propertyRu", "Удерживает один напев и возвращает его у воды"))
        }
        if (accepted(journal, 3) != null) memory = ChantalWorldMemory.withFact(memory, "keepsakes",
            fact(3, "wooden_light", "Деревянный огонёк Брамбла — память о письме и свете у переправы"))
        return memory
    }
